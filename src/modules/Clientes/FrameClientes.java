    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        int selectedRow = table1.getSelectedRow();
        if (selectedRow != -1) {
            // Obtener el ID del cliente seleccionado
            String idCliente = table1.getValueAt(selectedRow, 0).toString();

            // Mostrar un cuadro de diálogo de confirmación
            int respuesta = JOptionPane.showConfirmDialog(
                    null,
                    "¿Está seguro de que desea eliminar el cliente?",
                    "Confirmar eliminación",
                    JOptionPane.YES_NO_OPTION);

            // Comprobar la respuesta del usuario
            if (respuesta == JOptionPane.YES_OPTION) {
                // El usuario ha confirmado la eliminación
                String nombre = table1.getValueAt(selectedRow, 1).toString();
                String direccion = table1.getValueAt(selectedRow, 4).toString();
                String telefono = table1.getValueAt(selectedRow, 5).toString();
                cliented cl = new cliented();
                cl.EliminarCliente(idCliente, nombre, telefono, direccion);
                JOptionPane.showMessageDialog(null, "Cliente eliminado exitosamente.");
                ListarClientes();
            } else {
                // El usuario ha cancelado la eliminación
                JOptionPane.showMessageDialog(null, "Eliminación cancelada.");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Por favor, seleccione un cliente para eliminar.");
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        int selectedRow = table1.getSelectedRow();

        if (selectedRow != -1) {
            String idCliente = table1.getValueAt(selectedRow, 0).toString();
            String nombre = table1.getValueAt(selectedRow, 1).toString();
            String apellidop = table1.getValueAt(selectedRow, 2).toString();
            String apellidom = table1.getValueAt(selectedRow, 3).toString();
            String direccion = table1.getValueAt(selectedRow, 4).toString();
            String telefono = table1.getValueAt(selectedRow, 5).toString();

            // Crear un panel para editar los datos del cliente
            JPanel panel = new JPanel();
            panel.setLayout(new GridLayout(6, 2));

            JLabel nombreLabel = new JLabel("Nombre:");
            JTextField nombreField = new JTextField(15);
            nombreField.setText(nombre);

            JLabel apellidopLabel = new JLabel("Apellido Paterno:");
            JTextField apellidopField = new JTextField(15);
            apellidopField.setText(apellidop);

            JLabel apellidomLabel = new JLabel("Apellido Materno:");
            JTextField apellidomField = new JTextField(15);
            apellidomField.setText(apellidom);

            JLabel direccionLabel = new JLabel("Dirección:");
            JTextField direccionField = new JTextField(15);
            direccionField.setText(direccion);

            JLabel telefonoLabel = new JLabel("Teléfono:");
            JFormattedTextField telefonoField = new JFormattedTextField(createFormatter("##########"));
            telefonoField.setText(telefono);

            // Agregar los componentes al panel
            panel.add(nombreLabel);
            panel.add(nombreField);
            panel.add(apellidopLabel);
            panel.add(apellidopField);
            panel.add(apellidomLabel);
            panel.add(apellidomField);
            panel.add(direccionLabel);
            panel.add(direccionField);
            panel.add(telefonoLabel);
            panel.add(telefonoField);

            int result = JOptionPane.showConfirmDialog(null, panel, "Editar datos del cliente", JOptionPane.OK_CANCEL_OPTION);

            if (result == JOptionPane.OK_OPTION) {
                String nuevoNombre = nombreField.getText();
                String nuevoApellidop = apellidopField.getText();
                String nuevoApellidom = apellidomField.getText();
                String nuevaDireccion = direccionField.getText();
                String nuevoTelefonoStr = telefonoField.getText().replaceAll("[^0-9]", "");

                if (nuevoNombre.isEmpty() || nuevoTelefonoStr.isEmpty() || nuevaDireccion.isEmpty()) {
                    JOptionPane.showMessageDialog(null, "Ninguno de los campos puede estar incompleto. Por favor, complete todos los campos.");
                } else if (nuevoTelefonoStr.length() != 10) {
                    JOptionPane.showMessageDialog(null, "El número de teléfono debe tener 10 dígitos.");
                } else {
                    cliented cd = new cliented();
                    clientes cl = new clientes(nuevoNombre, nuevoApellidop, nuevoApellidom, nuevaDireccion, nuevoTelefonoStr);

                    boolean edicionExitosa = cd.actualizarCliente(idCliente, cl);

                    if (edicionExitosa) {
                        JOptionPane.showMessageDialog(null, "Cliente editado con éxito");
                        LimpiarTable();
                        ListarClientes();
                    } else {
                        JOptionPane.showMessageDialog(null, "Error al editar el cliente");
                    }
                }
            }
        } else {
            JOptionPane.showMessageDialog(null, "Por favor, seleccione un cliente para editar.");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        JPanel panel = new JPanel();
        panel.setLayout(new GridLayout(5, 2));
        panel.add(new JLabel("Nombre:"));
        JTextField nombreField = new JTextField(15);
        panel.add(nombreField);

        panel.add(new JLabel("Apellido Paterno:"));
        JTextField appField = new JTextField(15);
        panel.add(appField);

        panel.add(new JLabel("Apellido Materno:"));
        JTextField apmField = new JTextField(15);
        panel.add(apmField);

        panel.add(new JLabel("Dirección:"));
        JTextField direccionField = new JTextField(15);
        panel.add(direccionField);

        panel.add(new JLabel("Teléfono:"));
        JFormattedTextField telefonoField = new JFormattedTextField(createFormatter("##########"));
        panel.add(telefonoField);

        int result = JOptionPane.showConfirmDialog(null, panel, "Ingrese los datos del proveedor", JOptionPane.OK_CANCEL_OPTION);

        if (result == JOptionPane.OK_OPTION) {
            String nombre = nombreField.getText();
            String apellidop = appField.getText();
            String apellidom = apmField.getText();
            String direccion = direccionField.getText();
            String telefonoStr = telefonoField.getText().replaceAll("[^0-9]", "");
            String correo = ""; // Añadí inicialización para evitar errores
            String contraseña = ""; // Añadí inicialización para evitar errores
            String status = "tienda"; // Añadí inicialización para evitar errores

            if (nombre.isEmpty() || telefonoStr.isEmpty() || direccion.isEmpty() ) {
                JOptionPane.showMessageDialog(null, "Ninguno de los campos puede estar vacío. Por favor, complete todos los campos.");
            } else if (telefonoStr.length() != 10) {
                JOptionPane.showMessageDialog(null, "El número de teléfono debe tener 10 dígitos.");
            } else {
                cliented pr = new cliented();

                if (pr.clienteYaExisteEnBD(nombre)) { // Cambié 'marca' a 'nombre'
                    JOptionPane.showMessageDialog(null, "El cliente ya existe en la base de datos. Por favor, introduzca un nombre diferente.");
                } else {
                    clientes cl = new clientes(nombre, apellidop, apellidom, direccion, telefonoStr, correo, contraseña, status);

                    boolean registroExitoso = pr.RegistrarCliente(cl);

                    if (registroExitoso) {
                        JOptionPane.showMessageDialog(null, "Cliente registrado con éxito");
                        LimpiarTable();
                        ListarClientes();
                        btnBorrar.setEnabled(false);
                    } else {
                        JOptionPane.showMessageDialog(null, "Error al registrar el cliente");
                    }
                }
            }
        }
    }//GEN-LAST:event_btnAgregarActionPerformed

