    private void filtrarTabla() {
        String filtro = txtNombre.getText().toLowerCase();
        DefaultTableModel model = (DefaultTableModel) table1.getModel();
        model.setRowCount(0);

        for (int i = 0; i < clienteList.size(); i++) {
            String nombre = clienteList.get(i).getNombre().toLowerCase();
            String apellidoPaterno = clienteList.get(i).getApellidop().toLowerCase();
            String nombreCompleto = nombre + " " + apellidoPaterno;

            if (clienteList.get(i).getId_C() != null && !clienteList.get(i).getId_C().equals("1") && nombreCompleto.contains(filtro)) {
                Object[] ob = new Object[6];
                ob[0] = clienteList.get(i).getId_C();
                ob[1] = clienteList.get(i).getNombre();
                ob[2] = clienteList.get(i).getApellidop();
                ob[3] = clienteList.get(i).getApellidom();
                ob[4] = clienteList.get(i).getDireccion();
                ob[5] = clienteList.get(i).getTelefono();
                model.addRow(ob);
            }
        }
    }

    public void ListarClientes() {
        cliented proDAO = new cliented();
        clienteList = proDAO.listarClientes();
       
        DefaultTableModel model = (DefaultTableModel) table1.getModel();
        model.setRowCount(0);
        for (int i = 0; i < clienteList.size(); i++) {
            Object[] ob = new Object[6];
            ob[0] = clienteList.get(i).getId_C();
            ob[1] = clienteList.get(i).getNombre();
            ob[2] = clienteList.get(i).getApellidop();
            ob[3] = clienteList.get(i).getApellidom();
            ob[4] = clienteList.get(i).getDireccion();
            ob[5] = clienteList.get(i).getTelefono();
            model.addRow(ob);
        }
    }

